#!/usr/bin/env python3
"""Prompt reuse from a recurrent-state checkpoint (tinyllm.runner.checkpoints) against the calls it replaces.

    DEV=KFD+AMD uv run python tools/checkpoint_check.py [model.gguf] [--drafter DFlash2.gguf] [--chunk 128]
    DEV=KFD+AMD uv run python tools/checkpoint_check.py <Flash-Next shard 1> --mtp find --speculative 4 --chunk 1024

Greedy requests, decoded the way the engine decodes on this device (speculative cycles when the model has an
MTP block or a drafter is given, else sampling on the GPU):

1. a prompt of two and a half chunks, then some tokens;
2. the same prompt followed by other tokens, as an agent's next request looks when the chat template renders the
   reply differently: it must resume at the checkpoint before the prompt's last chunk;
3. the prompt and part of request 1's reply, then other tokens: it must resume at a checkpoint taken while
   decoding;
4. requests 1 and 2 again with an unrelated request of one chunk between them (a client's title request, say): the
   conversation must run that chunk again and then jump to its checkpoint.

Each resumed request must give the same logits, bit for bit, as running the same calls from scratch without the
detour, and request 2 the same tokens. Exits non-zero on any difference.

Where the session pads a prompt's last call (Qwen3.8-Flash-Next with its MTP block, `--mtp`), request 2's
checkpoint is the state that call kept inside it, 256 rows before its end. No sequence of calls ends in exactly
that state, so request 2 is compared twice: bit for bit with resuming after a single decode step instead of
request 1's reply (what ran in between must not matter), and up to rounding with calls that end at the checkpoint
(the same top token, or a tie within the difference). The other requests stay bit for bit.
"""

from __future__ import annotations

import argparse
import sys
import time

import numpy as np

GREEDY = [0.0, 1.0, 1.0, 0.0, 0.0]
CODE = """fn reverse(head: Option<Box<Node>>) -> Option<Box<Node>> {
    let mut prev = None;
    let mut cur = head;
    while let Some(mut node) = cur {
        cur = node.next.take();
        node.next = prev;
        prev = Some(node);
    }
    prev
}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("model", nargs="?", default=None, help="default: the dev model (tests/conftest.py)")
    ap.add_argument("--drafter", default=None, help="a DFlash2 GGUF to draft with instead of the MTP block")
    ap.add_argument(
        "--mtp", default=None, help="the MTP block's GGUF when the model does not carry it; 'find': as serve"
    )
    ap.add_argument("--speculative", type=int, default=None, help="drafts per cycle (default: 3 MTP, 7 DFlash2)")
    ap.add_argument("--chunk", type=int, default=32)
    ap.add_argument("--tokens", type=int, default=60, help="tokens generated by request 1")
    ap.add_argument("--programs", default=None, help="keep the compiled programs in this directory between runs")
    args = ap.parse_args()
    sys.stdout.reconfigure(line_buffering=True)  # type: ignore[union-attr]

    from pathlib import Path

    from tinyllm.runner.upstream import UpstreamRunner
    from tinyllm.server.serve import DEFAULT_DRAFTS, DFLASH_DRAFTS, find_mtp, has_mtp
    from tinyllm.weights.resolve import find_model

    path = find_model(args.model or "Qwen3.5-0.8B-Q8_0.gguf")
    drafter = Path(args.drafter).expanduser() if args.drafter else None
    mtp = None
    if args.mtp and not drafter:
        mtp = find_mtp(path) if args.mtp == "find" else Path(args.mtp).expanduser()
        if mtp is None:
            raise SystemExit(f"no MTP block found for {path.name}")
    k = args.speculative
    if k is None:
        k = DFLASH_DRAFTS if drafter else DEFAULT_DRAFTS if mtp or has_mtp(path) else 0
    start = time.perf_counter()
    runner = UpstreamRunner(
        path,
        4096,
        chunk=args.chunk,
        speculative=k,
        drafter=drafter if k else None,
        checkpoints=4,
        checkpoint_every=24,
        mtp_path=mtp if k else None,
        programs=args.programs,
    )
    padded = bool(runner.session.pads)  # the prompt's last call is padded and keeps the checkpoint's state inside
    runner.warmup()
    mode = f"{runner.speculative} drafts per cycle" if runner.speculative else "GPU sampling"
    mode = mode if runner.speculative or runner.device_sampling else "host sampling"
    print(f"tinyllm checkpoint check: {path.name}, {mode}, ready in {time.perf_counter() - start:.0f} s")
    tok = runner.session.tokenizer()
    chunk = args.chunk
    a = (tok.encode(CODE) * (3 * chunk))[: 2 * chunk + chunk // 2]
    other = tok.encode(" Now write it with an iterator instead, and add a test.")

    def step(last: int) -> list[int]:
        """Feed `last` and return the greedy tokens the step produces, the way the engine decodes on this device."""
        if runner.speculative:
            rows, m = runner.feed_speculative(last, [GREEDY] * (runner.speculative + 1))
            return [int(rows[j, 0]) for j in range(m + 1)]
        if runner.device_sampling:
            return [int(runner.feed_sampled(last, GREEDY)[0])]
        return [int(runner.feed([last]).argmax())]

    def decode(logits: np.ndarray, n: int) -> list[int]:
        """At least `n` greedy tokens after `logits` (the prompt's)."""
        out = [int(logits.argmax())]
        while len(out) < n:
            out += step(out[-1])
        return out

    def request(prompt: list[int], n: int) -> tuple[int, np.ndarray, list[int]]:
        cached = runner.begin(prompt)
        logits = runner.feed(prompt[cached:]).copy()
        return cached, logits, decode(logits, n)

    failures = 0

    def check(name: str, ok: bool, detail: str = "") -> None:
        nonlocal failures
        failures += not ok
        print(f"  {name}: {'same' if ok else 'FAIL'} {detail}")

    request(a, args.tokens)
    held = list(runner.tokens)
    positions = [c.pos for c in runner.checkpoints.items]
    print(f"request 1: {len(a)} prompt tokens, {len(held) - len(a)} decoded; checkpoints at {positions}")

    b = a + other
    cached, logits_b, out_b = request(b, 16)
    # the checkpoint before request 1's last prefill call: the last chunk's start, or with a short-call program the
    # last multiple of its length (tinyllm.tg.upstream.UpstreamSession.prefill)
    small = runner.session.small_chunk
    expected = (len(a) - 1) // small * small if small else (len(a) - 1) // chunk * chunk
    ok = cached == expected
    failures += not ok
    print(f"request 2: resumed at {cached} (expected {expected}){'' if ok else ' FAIL'}")
    if padded:  # resumed after one decode step instead of the reply: what ran in between must not matter
        runner.forget()
        request(a, 2)
        soon, at_once, out_at_once = request(b, 16)
        same = soon == cached and np.array_equal(logits_b, at_once)
        diff = f"(resumed at {soon}, max diff {np.abs(logits_b - at_once).max():.3g})"
        check("logits after the prompt, against resuming after one decode step", same, diff)
        check("tokens", out_b[:16] == out_at_once[:16], f"{tok.decode(out_b[:16])!r}")
    runner.forget()  # the same calls from scratch
    runner.begin(b)
    runner.feed(b[:cached], following=b[cached])
    ref = runner.feed(b[cached:]).copy()
    worst = float(np.abs(logits_b - ref).max())
    if padded:  # the state kept inside a call against the state calls ending there leave: equal up to rounding
        tie = float(ref.max() - ref[int(logits_b.argmax())]) <= worst
        name = "logits after the prompt, against calls ending at the checkpoint: the same top token or a tie"
        check(name, int(logits_b.argmax()) == int(ref.argmax()) or tie, f"(max diff {worst:.3g}, rounding)")
        ref_out = decode(ref, 16)
        agree = next((i for i, (x, y) in enumerate(zip(out_b, ref_out, strict=False)) if x != y), 16)
        print(f"  tokens against those calls: the first {min(agree, 16)} of 16 the same")
    else:
        check("logits after the prompt", np.array_equal(logits_b, ref), f"(max diff {worst:.3g})")
        ref_out = decode(ref, 16)
        check("tokens", out_b[:16] == ref_out[:16], f"{tok.decode(out_b[:16])!r}")

    # request 3: back to request 1's sequence, then part of its reply and other tokens
    request(a, args.tokens)
    check("request 1 again", runner.tokens == held)
    # a decode checkpoint a few tokens short of the end, so the request departs from the held tokens after it
    decoding = [c.pos for c in runner.checkpoints.items if len(a) < c.pos <= len(held) - 3]
    if not decoding:
        print(f"  FAIL: no checkpoint taken while decoding ({[c.pos for c in runner.checkpoints.items]})")
        return 1
    c = decoding[-1]
    p3 = held[: c + 2] + other
    cached = runner.begin(p3)
    ok = cached == c
    failures += not ok
    print(f"request 3: resumed at {cached} (expected the decode checkpoint at {c}){'' if ok else ' FAIL'}")
    resumed = runner.feed(p3[cached:]).copy()
    runner.forget()
    runner.begin(a)
    replay = [int(runner.feed(a).argmax())]  # then request 1's decode steps again, up to the checkpoint
    while len(runner.tokens) < c:
        replay += step(replay[-1])
    if len(runner.tokens) != c:
        print(f"  FAIL: the replay of request 1 reached {len(runner.tokens)}, not {c}")
        return 1
    if runner.begin(p3) != c:  # extends what the state holds: no checkpoint is loaded
        print(f"  FAIL: the replay did not continue at {c}")
        return 1
    ref = runner.feed(p3[c:]).copy()
    check("logits after the prompt", np.array_equal(resumed, ref), f"(max diff {np.abs(resumed - ref).max():.3g})")

    # request 4: requests 1 and 2 with another request in between, which overwrites the first chunk's positions
    side = (tok.encode("Give this conversation a title of five words. ") * chunk)[:chunk]
    runner.forget()
    request(a, args.tokens)
    resumed_at, ref, _ = request(b, 0)  # without the interruption
    runner.forget()
    request(a, args.tokens)
    request(side, 0)
    start = runner.begin(b)
    ok = start == 0 and runner.reused == resumed_at - chunk
    failures += not ok
    print(
        f"request 4: after a {chunk}-token request, fed from {start} and {runner.reused} tokens reused "
        f"(expected 0 and {resumed_at - chunk}){'' if ok else ' FAIL'}"
    )
    logits = runner.feed(b[start:]).copy()
    check("logits after the prompt", np.array_equal(logits, ref), f"(max diff {np.abs(logits - ref).max():.3g})")
    passed = "all identical" + (", request 2's checkpoint inside a call up to rounding" if padded else "")
    print("tinyllm checkpoint check: " + (passed if not failures else f"{failures} FAIL"))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
